const RESOURCE_KEYS = [
  ["payment", "payment"],
  ["invoice", "invoice"],
  ["transfer", "transfer"],
  ["bill", "bill"],
  ["anticipation", "receivable_anticipation"],
  ["receivableAnticipation", "receivable_anticipation"],
  ["mobilePhoneRecharge", "mobile_phone_recharge"],
  ["accountStatus", "account_status"],
  ["subscription", "subscription"],
  ["checkout", "checkout"],
  ["pixAutomaticRecurringAuthorization", "pix_automatic_authorization"],
  ["pixAutomaticRecurringPaymentInstruction", "pix_automatic_instruction"],
  ["pixCredit", "pix_credit"],
  ["balance", "balance"],
  ["internalTransfer", "internal_transfer"],
  ["accessToken", "access_token"],
] as const

export function asaasResourceFromPayload(payload: Record<string, unknown>) {
  for (const [key, type] of RESOURCE_KEYS) {
    const value = payload[key]
    if (value && typeof value === "object") return { type, value: value as Record<string, unknown> }
  }
  return { type: "unknown", value: {} as Record<string, unknown> }
}

export function asaasEventResourceLabel(eventType: string) {
  if (eventType.startsWith("PAYMENT_")) return "Cobranca"
  if (eventType.startsWith("INVOICE_")) return "Nota fiscal"
  if (eventType.startsWith("TRANSFER_")) return "Transferencia"
  if (eventType.startsWith("BILL_")) return "Pagamento de conta"
  if (eventType.startsWith("RECEIVABLE_ANTICIPATION_")) return "Antecipacao"
  if (eventType.startsWith("MOBILE_PHONE_RECHARGE_")) return "Recarga"
  if (eventType.startsWith("ACCOUNT_STATUS_")) return "Situacao da conta"
  if (eventType.startsWith("SUBSCRIPTION_")) return "Assinatura"
  if (eventType.startsWith("CHECKOUT_")) return "Checkout"
  if (eventType.startsWith("PIX_AUTOMATIC_")) return "Pix Automatico"
  if (eventType.startsWith("PIX_CREDIT_")) return "Credito Pix"
  if (eventType.startsWith("BALANCE_")) return "Saldo"
  if (eventType.startsWith("INTERNAL_TRANSFER_")) return "Movimentacao interna"
  if (eventType.startsWith("ACCESS_TOKEN_")) return "Chave de API"
  return "Evento Asaas"
}
